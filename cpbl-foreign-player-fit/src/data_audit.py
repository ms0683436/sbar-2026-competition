"""Phase 0 — quantitative data-availability audit.

Produces reports/data_audit_summary.md: per source, per season, the share of
non-missing values for every field the analysis relies on, row/game counts and
date ranges. The narrative Go/No-Go lives in reports/data_feasibility.md.
"""
from __future__ import annotations

import glob

import pandas as pd

from . import milb_loader, rebas_loader
from .common import md_table, path, processed, raw


def _cov(df: pd.DataFrame, cols: list[str], by="season") -> pd.DataFrame:
    out = df.groupby(by)[cols].agg(lambda s: s.notna().mean()).T
    out.columns = [str(c) for c in out.columns]
    return out.reset_index(names="field")


def cpbl_audit() -> tuple[pd.DataFrame, pd.DataFrame]:
    d = rebas_loader.load()
    bip = d[d.pa_end & d.pitch_code.eq("H")]
    meta = d.groupby("season").agg(games=("game_id", "nunique"), pitches=("pa_id", "size"), pas=("pa_end", "sum"),
                                   first=("date", "min"), last=("date", "max"),
                                   pitchers=("pitcher_id", "nunique"), batters=("batter_id", "nunique")).reset_index()
    cov = _cov(d, ["pitch_type_raw", "pitch_type", "velo_kmh", "coord_x", "coord_y", "p_throws", "stand",
                   "pitcher_id", "batter_id"])
    cov_bip = _cov(bip, ["hardness", "trajectory"])
    cov_bip["field"] = cov_bip.field + " (balls in play)"
    return meta, pd.concat([cov, cov_bip])


def aaa_audit() -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    d = milb_loader.load()
    meta = pd.read_csv(processed("aaa_pitches_audit.csv"))
    cov = _cov(d, ["pitch_type_raw", "pitch_type", "velo_mph", "release_spin_rate", "release_extension", "pfx_x",
                   "pfx_z", "plate_x", "in_zone", "p_throws", "stand"])
    bip = d[d.pa_end & d.pa_event.isin(["1B", "2B", "3B", "HR", "OUT", "SF"])]
    cb = _cov(bip, ["launch_speed", "launch_angle"])
    cb["field"] = cb.field + " (balls in play)"
    # fields present in the raw file but empty (checked on one month to keep it cheap)
    f = sorted(glob.glob(str(raw("milb_pbp", "2025_4_aaa_pbp.csv"))))
    empty = pd.DataFrame()
    if f:
        r = pd.read_csv(f[0], usecols=["estimated_woba_using_speedangle", "estimated_ba_using_speedangle",
                                       "woba_value", "delta_run_exp", "events", "launch_speed_angle"],
                        low_memory=False)
        empty = r.notna().mean().rename("share_non_missing_2025_04").rename_axis("raw_field").reset_index()
    return meta, pd.concat([cov, cb]), empty


def season_audit() -> pd.DataFrame:
    rows = []
    for y in (2025, 2026):
        for kind in ("batting", "pitching"):
            s = milb_loader.season_stats(kind, y)
            pa = s.batting_PA.sum() if kind == "batting" else s.pitching_BF.sum()
            rows.append({"file": f"{y}_aaa_season_{kind}_stats.csv", "rows": len(s), "teams": s.team_id.nunique(),
                         "PA_or_BF": int(pa)})
    for y in (2025, 2026):
        g = milb_loader.game_logs(y)
        rows.append({"file": f"{y} AAA player game logs", "rows": len(g), "teams": g.team_id.nunique(),
                     "PA_or_BF": int(g.batting_PA.sum()), "first": str(g.game_date.min().date()),
                     "last": str(g.game_date.max().date()), "raw_rows_before_dedup": g.attrs.get("n_raw")})
    return pd.DataFrame(rows)


def run() -> str:
    parts = ["# Data audit summary (auto-generated by `python -m src.data_audit`)\n",
             "Shares are fraction of rows with a non-missing value.\n"]
    m, c = cpbl_audit()
    parts += ["## CPBL — REBAS Open Data pitch-by-pitch\n", md_table(m), "\n", md_table(c), "\n"]
    m, c, e = aaa_audit()
    parts += ["## AAA — MLB Stats API MiLB feed (GitHub mirror), pitch level\n", md_table(m), "\n", md_table(c), "\n"]
    if len(e):
        parts += ["Raw columns present but EMPTY in the mirror (2025-04 file):\n", md_table(e), "\n"]
    parts += ["## AAA — season totals and game logs\n", md_table(season_audit()), "\n"]
    el = pd.read_csv(processed("mlb_season_audit.csv"))
    parts += ["## MLB regular season (Retrosheet event files -> cwdaily)\n", md_table(el), "\n"]
    text = "\n".join(parts)
    (path("reports") / "data_audit_summary.md").write_text(text, encoding="utf-8")
    return text


if __name__ == "__main__":
    print(run())
