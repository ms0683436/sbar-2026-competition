"""Amendment 7b, item 4 — REBAS broadcast velocity vs stats.cpbl.com.tw Trackman.

Same pitchers, fastballs: REBAS 2025 FF + SI average (km/h, hand-recorded broadcast speed)
against the site's 2026 一軍例行賽 "快速球" average (Trackman). The comparison crosses seasons,
so it mixes a measurement offset with true year-to-year change; the AAA Statcast same-pitcher
2025 -> 2026 fastball change is the reference for the latter (config amendment7b.velocity).
Descriptive only: nothing here changes Fit, the ranking or the picks.

Usage:  python -m src.velocity_calibration
"""
from __future__ import annotations

import json

import numpy as np
import pandas as pd

from . import cpbl_site, milb_loader
from .common import config, md_table, path, processed

KMH = 1.609344


def cfg() -> dict:
    return config()["amendment7b"]


def rebas_fastballs(types) -> pd.DataFrame:
    v = cfg()["velocity"]
    c = pd.read_parquet(processed("cpbl_pitches.parquet"),
                        columns=["season", "pitcher_id", "pitcher_name", "pitch_type", "velo_kmh"])
    c = c[(c.season == v["rebas_season"]) & c.pitch_type.isin(types) & c.velo_kmh.notna()]
    g = c.groupby("pitcher_id").agg(rebas_name=("pitcher_name", "first"), rebas_n=("velo_kmh", "size"),
                                    rebas_kmh=("velo_kmh", "mean"))
    g["rebas_name"] = g.rebas_name.map(cpbl_site.clean_name)
    return g[g.rebas_n >= v["min_pitches"]].reset_index()


def site_fastballs() -> pd.DataFrame:
    v = cfg()["velocity"]
    s = cpbl_site.velocity()
    s = s[(s.season == v["site_season"]) & s.pitch_group.eq("快速球") & s.default_game_type.eq("一軍例行賽")
          & (s.pitches >= v["min_pitches"]) & s.velo_avg_kmh.notna()]
    return s[["site_id", "site_name", "pitches", "velo_avg_kmh"]].rename(columns={"pitches": "site_n",
                                                                               "velo_avg_kmh": "site_kmh"})


def pairs(types) -> pd.DataFrame:
    r, s = rebas_fastballs(types), site_fastballs()
    r = r[~r.rebas_name.duplicated(keep=False)]
    s = s[~s.site_name.duplicated(keep=False)]
    d = r.merge(s, left_on="rebas_name", right_on="site_name", how="inner")
    d["diff_kmh"] = d.site_kmh - d.rebas_kmh
    return d


def aaa_change() -> dict:
    """Same-pitcher AAA Statcast fastball (FF + SI) change 2025 -> 2026, km/h."""
    v = cfg()["velocity"]
    a = milb_loader.load()
    a = a[a.season.isin([2025, 2026]) & a.pitch_type.isin(v["rebas_fastball"]) & a.velo_mph.notna()]
    g = a.groupby(["pitcher_id", "season"]).velo_mph.agg(["size", "mean"]).unstack()
    g = g[(g[("size", 2025)] >= v["min_pitches"]) & (g[("size", 2026)] >= v["min_pitches"])]
    d = (g[("mean", 2026)] - g[("mean", 2025)]) * KMH
    return {"n": int(len(d)), "mean_kmh": float(d.mean()), "median_kmh": float(d.median()), "sd_kmh": float(d.std())}


def _boot(x: np.ndarray, rng, draws: int, ci: float) -> tuple[float, float]:
    m = [x[rng.integers(0, len(x), len(x))].mean() for _ in range(draws)]
    a = (1 - ci) / 2
    return float(np.quantile(m, a)), float(np.quantile(m, 1 - a))


def run() -> dict:
    v, b = cfg()["velocity"], cfg()["bootstrap"]
    rng = np.random.default_rng(b["seed"])
    ref = aaa_change()
    res = {"aaa_same_pitcher_change_2025_2026": ref, "variants": []}
    main = None
    for types in [v["rebas_fastball"]] + v["sensitivity"]:
        d = pairs(types)
        x = d.diff_kmh.to_numpy()
        lo, hi = _boot(x, rng, b["draws"], b["ci"])
        slope = float(np.polyfit(d.rebas_kmh, d.site_kmh, 1)[0]) if len(d) > 2 else np.nan
        row = {"rebas_types": "+".join(types), "n": len(d), "mean_diff_kmh": float(x.mean()), "ci_lo": lo, "ci_hi": hi,
               "median_diff_kmh": float(np.median(x)), "slope_site_on_rebas": slope,
               "offset_kmh": float(x.mean() - ref["mean_kmh"])}
        res["variants"].append(row)
        if main is None:
            main = d
    off = res["variants"][0]["offset_kmh"]
    res["d4_covered"] = abs(off) <= v["d4_threshold_kmh"]
    main.to_csv(processed("velocity_calibration_pairs.csv"), index=False)
    processed("velocity_calibration.json").write_text(json.dumps(res, indent=2, ensure_ascii=False))
    lines = ["# Velocity calibration (amendment 7b item 4; generated by `python -m src.velocity_calibration`)", "",
             f"REBAS {v['rebas_season']} broadcast speed vs stats.cpbl.com.tw {v['site_season']} Trackman "
             "(一軍例行賽 快速球), same pitchers, km/h. Site data used without written authorization (limitations L10). "
             "資料來源：野球革命 Rebas Open Data.", "",
             md_table(pd.DataFrame(res["variants"]), floatfmt=".2f"), "",
             f"AAA Statcast same-pitcher FF+SI change 2025 -> 2026: mean {ref['mean_kmh']:+.2f} km/h "
             f"(median {ref['median_kmh']:+.2f}, n = {ref['n']}). offset = mean diff - this change.", "",
             f"|offset| {'<=' if res['d4_covered'] else '>'} {v['d4_threshold_kmh']} km/h: findings D4 (±1 mph) "
             f"{'covers' if res['d4_covered'] else 'does not cover'} the calibration.", ""]
    (path("reports") / "velocity_calibration.md").write_text("\n".join(lines), encoding="utf-8")
    return res


if __name__ == "__main__":
    print(json.dumps(run(), indent=2, ensure_ascii=False))
